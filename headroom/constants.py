# AWS ARN Regex Pattern
# Pattern to extract 12-digit account ID from AWS ARN
# Format: arn:partition:service:region:account-id:resource
#
# The service segment is deliberately unconstrained: a resource policy
# principal can be an STS session ARN (arn:aws:sts::{account}:assumed-role/...)
# as readily as an IAM one, and pinning the segment to `iam` drops the account.
# The partition is matched the same way, so GovCloud and China ARNs resolve.
# The account field is twelve ASCII digits, not Python's `\d`, which also
# accepts the digits of every other script; a condition value is never
# validated by AWS and reaches this pattern as written.
AWS_ARN_ACCOUNT_ID_PATTERN = r'^arn:aws[a-z0-9-]*:[^:]+:[^:]*:([0-9]{12}):'

# EC2 IMDSv2 Exemption Tag
# The tag the deny_ec2_imds_v1 SCP exempts on, via
# aws:RequestTag/ExemptFromIMDSv2 on the RunInstances request.
#
# The scan reads it off the INSTANCE, which is a proxy: the same
# TagSpecifications entry that exempts the launch is what puts the tag on the
# instance it creates. See get_ec2_imds_v1_analysis for what the proxy costs.
#
# The two halves are matched differently, and a scanner has to follow both.
# IAM matches condition key names - including the tag key after the slash -
# without regard to case, so `exemptfromimdsv2` exempts too. The value is
# compared with StringNotEquals, which is case-sensitive, so an instance
# tagged "True" is not exempt to enforcement and must not be reported exempt.
# Measured with RunInstances --dry-run: "true" allows the launch, "True"
# does not.
IMDS_EXEMPTION_TAG_KEY = "ExemptFromIMDSv2"
IMDS_EXEMPTION_TAG_VALUE = "true"

# The paved-road tag deny_eks_create_cluster_without_tag requires. Read by the
# same rule as the IMDS pair above: the key matches without regard to case,
# the value does not. The Terraform module spells both out again; changing
# one here does not change it there.
EKS_PAVED_ROAD_TAG_KEY = "PavedRoad"
EKS_PAVED_ROAD_TAG_VALUE = "true"

