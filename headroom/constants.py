# The first line of every .tf file Headroom writes, and the only thing that
# marks a file as Headroom's to delete.
#
# Ownership lives in the content rather than in the filename or a side manifest.
# A filename glob would claim a hand-written custom_scps.tf; a manifest is state
# that can be lost, at which point every generated file becomes an orphan, or go
# stale, at which point it names files that were never ours. The marker travels
# with the file it describes and cannot disagree with it.
#
# Matched as a whole first line, never as a substring: scps/README.md quotes this
# marker inside a code block while explaining it, so a substring scan deletes the
# document that describes it. The wording follows Go's `// Code generated ... DO NOT EDIT.`
# convention, which exists for exactly this purpose.
GENERATED_MARKER = "# Code generated by Headroom. DO NOT EDIT."
