"""
Organization Info Terraform Generation Module

Generates Terraform configuration files for AWS Organizations structure data
to support SCP/RCP deployment targeting.
"""

from typing import Dict, List, Optional, Set

from .utils import (
    account_id_local_name,
    make_account_base_names,
    make_ou_base_names,
    ou_id_local_name,
    ou_path_names,
)
from ..constants import GENERATED_MARKER
from ..types import OrganizationHierarchy, OrganizationalUnit, AccountOrgPlacement


def render_terraform_org_info(organization_hierarchy: OrganizationHierarchy) -> str:
    """
    Render grab_org_info.tf from an already-captured hierarchy.

    Nothing is written and nothing on disk is read. This renders the hierarchy
    the run captured, so the data sources describe the same organization
    placement just used.

    Args:
        organization_hierarchy: The run's captured organization hierarchy

    Returns:
        Complete Terraform configuration as a string
    """
    return _generate_terraform_content(organization_hierarchy)


def _generate_terraform_header() -> List[str]:
    """
    Generate file header and root OU data source.

    Returns:
        List of Terraform configuration lines for file header
    """
    return [
        # Unconditional, and first: reconciliation claims a file by this exact
        # line. grab_org_info.tf is written outside both policy workflows, so
        # without the marker it would look unmanaged and drift on forever.
        GENERATED_MARKER,
        "# Auto-generated Terraform configuration for AWS Organizations structure",
        "# Generated by Headroom for SCP/RCP deployment targeting",
        "",
        "# Get the root OU ID",
        'data "aws_organizations_organization" "org" {}',
        "",
        'data "aws_organizations_organizational_units" "root_ou" {',
        "  parent_id = data.aws_organizations_organization.org.roots[0].id",
        "}",
        "",
        "# Get the child OUs and accounts of each OU",
    ]


def _ordered_ou_ids(
    organizational_units: Dict[str, OrganizationalUnit],
    ou_base_names: Dict[str, str]
) -> List[str]:
    """
    Return OU IDs with every parent ahead of the children it introduces.

    A nested OU is resolved through a data source keyed on its parent, so the
    generated file reads top down. Siblings are ordered by name to keep the
    output stable between runs.

    Args:
        organizational_units: All OUs in the organization
        ou_base_names: OU ID -> Terraform identifier

    Returns:
        OU IDs, outermost first
    """
    children_by_parent: Dict[Optional[str], List[str]] = {}
    for ou_id, ou in organizational_units.items():
        parent = ou.parent_ou_id
        if parent not in organizational_units:
            parent = None
        children_by_parent.setdefault(parent, []).append(ou_id)

    def by_name(ou_ids: List[str]) -> List[str]:
        return sorted(ou_ids, key=lambda ou_id: ou_base_names[ou_id])

    ordered: List[str] = []
    pending = by_name(children_by_parent.get(None, []))
    while pending:
        ou_id = pending.pop(0)
        ordered.append(ou_id)
        pending[0:0] = by_name(children_by_parent.get(ou_id, []))

    return ordered


def _ou_ids_holding_accounts(
    accounts: Dict[str, AccountOrgPlacement],
    organizational_units: Dict[str, OrganizationalUnit]
) -> Set[str]:
    """
    Return the OUs that at least one account resolves through.

    Args:
        accounts: All accounts in the organization
        organizational_units: All OUs in the organization

    Returns:
        Set of OU IDs whose child-accounts data source is actually read
    """
    ou_ids: Set[str] = set()
    for account in accounts.values():
        parent_ou_id = account.parent_ou_id
        if parent_ou_id is not None and parent_ou_id in organizational_units:
            ou_ids.add(parent_ou_id)
    return ou_ids


def _generate_ou_data_sources(
    organizational_units: Dict[str, OrganizationalUnit],
    accounts: Dict[str, AccountOrgPlacement]
) -> List[str]:
    """
    Generate the per-OU data sources the locals below resolve against.

    An OU with child OUs exposes the list those children are found in, which
    is what lets an OU at any depth be resolved without hardcoding its ID. An
    OU holding accounts exposes its child accounts. Nothing is emitted for an
    OU that has neither, because nothing would read it.

    Args:
        organizational_units: All OUs in the organization
        accounts: All accounts in the organization

    Returns:
        List of Terraform data source blocks
    """
    content_parts: List[str] = []

    ou_base_names = make_ou_base_names(organizational_units)
    ous_holding_accounts = _ou_ids_holding_accounts(accounts, organizational_units)

    for ou_id in _ordered_ou_ids(organizational_units, ou_base_names):
        base_name = ou_base_names[ou_id]
        local_reference = f"local.{ou_id_local_name(base_name)}"
        ou = organizational_units[ou_id]

        has_child_ous = any(
            child_id in organizational_units for child_id in ou.child_ous
        )
        if has_child_ous:
            content_parts.extend([
                f'data "aws_organizations_organizational_units" "{base_name}_children" {{',
                f"  parent_id = {local_reference}",
                "}",
                "",
            ])

        if ou_id in ous_holding_accounts:
            content_parts.extend([
                f'data "aws_organizations_organizational_unit_child_accounts" "{base_name}_accounts" {{',
                f"  parent_id = {local_reference}",
                "}",
                "",
            ])

    return content_parts


def _generate_root_locals() -> List[str]:
    """
    Generate opening of locals block with root validation check.

    Returns:
        List of Terraform lines for locals block opening with root_ou_id
    """
    return [
        "locals {",
        "  # Validation check for root OU access",
        "  validation_check_root = (length(data.aws_organizations_organization.org.roots) == 1) ? \"All good. This is a no-op.\" : error(\"[Error] Expected exactly 1 root OU, found ${length(data.aws_organizations_organization.org.roots)}\")",
        "",
        "  # Root OU ID",
        "  root_ou_id = data.aws_organizations_organization.org.roots[0].id",
        "",
    ]


def _ou_siblings_reference(
    ou: OrganizationalUnit,
    organizational_units: Dict[str, OrganizationalUnit],
    ou_base_names: Dict[str, str]
) -> str:
    """
    Return the list of OUs an OU is found by name within.

    A top-level OU is one of the root's children. Any deeper OU is one of its
    own parent's children, reached through the data source that parent emits.

    Args:
        ou: OU being resolved
        organizational_units: All OUs in the organization
        ou_base_names: OU ID -> Terraform identifier

    Returns:
        Terraform expression evaluating to a list of OUs
    """
    parent_ou_id = ou.parent_ou_id
    if parent_ou_id is None or parent_ou_id not in organizational_units:
        return "data.aws_organizations_organizational_units.root_ou.children"

    parent_base_name = ou_base_names[parent_ou_id]
    return (
        "data.aws_organizations_organizational_units"
        f".{parent_base_name}_children.children"
    )


def _generate_ou_locals(
    organizational_units: Dict[str, OrganizationalUnit]
) -> List[str]:
    """
    Generate local variables for OU IDs, at every depth.

    Every OU gets an ID local, not only the ones directly under the root: a
    policy may land on any OU, and a policy targeting a local nobody declared
    is Terraform that will not plan.

    Args:
        organizational_units: All OUs in the organization

    Returns:
        List of Terraform lines for OU local variables with validations
    """
    content_parts: List[str] = []

    if not organizational_units:
        return content_parts

    ou_base_names = make_ou_base_names(organizational_units)

    content_parts.append("  # OU IDs by path from the root")

    for ou_id in _ordered_ou_ids(organizational_units, ou_base_names):
        ou = organizational_units[ou_id]
        base_name = ou_base_names[ou_id]
        path_label = " / ".join(ou_path_names(ou_id, organizational_units))
        siblings = _ou_siblings_reference(ou, organizational_units, ou_base_names)
        matches = f"[for ou in {siblings} : ou.id if ou.name == \"{ou.name}\"]"

        content_parts.extend([
            f"  # Validation for {path_label} OU",
            f"  validation_check_{base_name}_ou = (length({matches}) == 1) ? \"All good. This is a no-op.\" : error(\"[Error] Expected exactly 1 {path_label} OU, found ${{length({matches})}}\")",
            "",
            f"  {ou_id_local_name(base_name)} = [",
            f"    for ou in {siblings} :",
            f"    ou.id if ou.name == \"{ou.name}\"",
            "  ][0]",
            "",
        ])

    return content_parts


def _account_source_reference(
    account: AccountOrgPlacement,
    organizational_units: Dict[str, OrganizationalUnit],
    ou_base_names: Dict[str, str]
) -> Optional[str]:
    """
    Return the list of accounts an account is found by name within.

    An account resolves through its own parent OU, whatever that OU's depth.
    Resolving it through the top-level OU above it instead found nothing: the
    child-accounts data source lists an OU's immediate children only, so a
    nested account was absent from the very list that was searched for it.

    Args:
        account: Account being resolved
        organizational_units: All OUs in the organization
        ou_base_names: OU ID -> Terraform identifier

    Returns:
        Terraform expression evaluating to a list of accounts, or None when
        the account's parent OU is absent from the hierarchy
    """
    if account.parent_ou_id is None:
        # Accounts directly under the root belong to no OU, so there is no
        # OU child-accounts data source to resolve them through.
        return "data.aws_organizations_organization.org.accounts"

    if account.parent_ou_id not in organizational_units:
        return None

    base_name = ou_base_names[account.parent_ou_id]
    return (
        "data.aws_organizations_organizational_unit_child_accounts"
        f".{base_name}_accounts.accounts"
    )


def _generate_account_locals(
    accounts: Dict[str, AccountOrgPlacement],
    organizational_units: Dict[str, OrganizationalUnit]
) -> List[str]:
    """
    Generate local variables for account IDs.

    Args:
        accounts: All accounts in the organization
        organizational_units: All OUs (for name lookups)

    Returns:
        List of Terraform lines for account local variables with validations
    """
    content_parts: List[str] = []

    if not accounts:
        return content_parts

    content_parts.append("  # Account IDs by name")

    ou_base_names = make_ou_base_names(organizational_units)
    # Claims one Terraform identifier per account, so two names that fold
    # alike abort here rather than declare the same local twice.
    account_base_names = make_account_base_names(accounts)
    ordered_accounts = sorted(
        accounts.values(),
        key=lambda account: account.account_name
    )

    for account in ordered_accounts:
        accounts_source = _account_source_reference(
            account,
            organizational_units,
            ou_base_names
        )
        if accounts_source is None:
            continue

        safe_account_name = account_base_names[account.account_id]
        matches = (
            f"[for account in {accounts_source} : account.id "
            f"if account.name == \"{account.account_name}\"]"
        )
        content_parts.extend([
            f"  # Validation for {account.account_name} account",
            f"  validation_check_{safe_account_name}_account = (length({matches}) == 1) ? \"All good. This is a no-op.\" : error(\"[Error] Expected exactly 1 {account.account_name} account, found ${{length({matches})}}\")",
            "",
            f"  {account_id_local_name(safe_account_name)} = [",
            f"    for account in {accounts_source} :",
            f"    account.id if account.name == \"{account.account_name}\"",
            "  ][0]",
            "",
        ])

    return content_parts


def _generate_terraform_content(organization_hierarchy: OrganizationHierarchy) -> str:
    """
    Generate Terraform content with data sources derived from root_ou, no hardcoded IDs.

    Args:
        organization_hierarchy: Organization structure data from discover_organization()

    Returns:
        Complete Terraform configuration as string
    """
    content_parts = []

    content_parts.extend(_generate_terraform_header())

    content_parts.extend(
        _generate_ou_data_sources(
            organization_hierarchy.organizational_units,
            organization_hierarchy.accounts
        )
    )

    content_parts.extend(_generate_root_locals())

    content_parts.extend(
        _generate_ou_locals(organization_hierarchy.organizational_units)
    )

    content_parts.extend(
        _generate_account_locals(
            organization_hierarchy.accounts,
            organization_hierarchy.organizational_units
        )
    )

    content_parts.append("}")

    return "\n".join(content_parts) + "\n"
